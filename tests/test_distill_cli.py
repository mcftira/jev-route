class TestTheLifecycle:
    def test_every_stage_exits_zero(self, lifecycle: dict[str, Any]) -> None:
        for stage in ("export", "train", "evaluate", "package"):
            code, out, err = lifecycle[stage]
            assert code == 0, f"{stage} exited {code}: {err or out}"

    def test_no_stage_printed_a_traceback(self, lifecycle: dict[str, Any]) -> None:
        for stage in ("export", "train", "evaluate", "package"):
            _, out, err = lifecycle[stage]
            assert TRACEBACK not in out + err, f"{stage} leaked a traceback"

    def test_export_reports_the_rows_it_kept(self, lifecycle: dict[str, Any]) -> None:
        _, out, _ = lifecycle["export"]
        assert "dataset" in out.lower()
        rows = [line for line in lifecycle["dataset"].read_text(encoding="utf-8").splitlines() if line.strip()]
        assert len(rows) > 100, f"the export kept only {len(rows)} of 140 records"
        first = json.loads(rows[0])
        assert "features" in first or "text" in first

    def test_train_writes_an_artifact_directory(self, lifecycle: dict[str, Any]) -> None:
        model = lifecycle["model"]
        from jev_route.distill.artifact import ARTIFACT_KIND, ARTIFACT_SCHEMA_VERSION

        envelope = json.loads((model / "artifact.json").read_text(encoding="utf-8"))
        # Compared against the library's constants, not a literal copied from the docs:
        # the kind string is the loader's contract, and a test that hardcodes it would
        # keep passing after the loader stopped accepting it.
        assert envelope["kind"] == ARTIFACT_KIND
        assert envelope["artifact_schema_version"] == ARTIFACT_SCHEMA_VERSION
        assert envelope["mode"] == "features"
        assert envelope["contains_prompt_text"] is False, "a hash-mode log has no text to retain"
        assert sorted(model.glob("*.npy")), "the weights are not on disk"

    def test_evaluate_reports_the_four_heads(self, lifecycle: dict[str, Any]) -> None:
        _, payload, _ = lifecycle["evaluate_json"]
        heads = payload["report"]["heads"] if "report" in payload else payload["heads"]
        assert set(heads) >= {"complexity", "sensitivity", "domain", "pii"}

    def test_package_embeds_metrics_and_verifies_its_own_output(self, lifecycle: dict[str, Any]) -> None:
        _, out, _ = lifecycle["package"]
        assert "no pickle anywhere" in out
        artifact = lifecycle["artifact"]
        assert (artifact / "metrics.json").is_file(), "the packaged artifact carries no metrics.json"
        envelope = json.loads((artifact / "artifact.json").read_text(encoding="utf-8"))
        assert envelope["packaged_from"], "the artifact does not say what it was packaged from"

    def test_package_json_names_the_files_it_wrote(self, lifecycle: dict[str, Any]) -> None:
        code, payload, err = run_json(
            ["package", "--artifact", str(lifecycle["model"]), "--out", str(lifecycle["work"] / "packaged-json")]
        )
        assert code == 0, err
        assert payload["metrics_embedded"] is True
        assert set(payload["files"]) >= {"artifact.json", "metrics.json"}
        assert payload["bytes"] == sum(payload["files"].values())


