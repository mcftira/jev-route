class TestGraduation:
    def test_the_documented_gates_are_not_met_by_a_small_synthetic_model(self, lifecycle: dict[str, Any]) -> None:
        """Exit 1 and nothing written. A student trained on 140 mock decisions cannot graduate."""
        code, out, err = run(["graduate", "--artifact", str(lifecycle["artifact"])])
        assert code == 1, f"expected NOT READY, got {code}: {err or out}"
        assert "NOT READY" in out
        assert "min_samples" in out
        assert "WARNING" not in out, "no gate was relaxed, so there is nothing to warn about"
        assert not list(lifecycle["work"].glob("*graduated*")), "a policy was written by a run without --write"

    def test_the_gates_table_shows_requirement_and_measurement(self, lifecycle: dict[str, Any]) -> None:
        _, out, _ = lifecycle["graduate"]
        for gate in ("min_tier_agreement", "max_ece", "max_latency_ms", "min_samples"):
            assert gate in out, f"{gate} is missing from the report"
        assert "[ pass ]" in out or "[ FAIL ]" in out

    def test_a_relaxed_gate_is_never_silent(self, lifecycle: dict[str, Any]) -> None:
        """A READY verdict bought by moving the goalposts has to say so, loudly."""
        code, out, _ = run(
            [
                "graduate",
                "--artifact",
                str(lifecycle["artifact"]),
                "--min-tier-agreement",
                "0.0",
                "--max-ece",
                "1.0",
                "--max-latency-ms",
                "100000",
                "--min-samples",
                "1",
            ]
        )
        assert code == 0
        assert "VERDICT: READY" in out
        assert "WARNING" in out
        assert "NOT a promotion" in out
        for gate in ("min_tier_agreement", "max_ece", "max_latency_ms", "min_samples"):
            assert f"- {gate}:" in out, f"{gate} was relaxed but not reported"

    def test_the_relaxed_gates_appear_in_the_json_too(self, lifecycle: dict[str, Any]) -> None:
        _, payload, _ = lifecycle["graduate_json"]
        assert [line.split(":")[0] for line in payload["gates_relaxed"]] == ["min_samples"]
        assert payload["wrote"] is None, "--json without --write must not claim a swap"

    def test_relaxing_one_gate_does_not_buy_a_pass(self, lifecycle: dict[str, Any]) -> None:
        """``--min-samples 1`` alone still leaves the student short of the other three gates."""
        _, payload, _ = lifecycle["graduate_json"]
        assert payload["ready"] is False
        failed = [c["name"] for c in payload["checks"] if not c["passed"]]
        assert "min_samples" not in failed
        assert failed, "at least one gate should still fail on 140 synthetic decisions"

    def test_exactly_one_relaxed_gate_reports_exactly_one_line(self, lifecycle: dict[str, Any]) -> None:
        _, out, _ = lifecycle["graduate"]
        assert "WARNING: 1 of the 4 gates were relaxed" in out
        assert out.count("in the docs") == 1
        assert "min_samples: 1 on the command line, 500 in the docs (floor lowered)" in out

    def test_tightening_a_gate_is_not_reported_as_relaxing_it(self, lifecycle: dict[str, Any]) -> None:
        code, out, _ = run(
            ["graduate", "--artifact", str(lifecycle["artifact"]), "--max-ece", "0.01", "--min-samples", "500"]
        )
        assert code == 1
        assert "WARNING" not in out, "a stricter gate cannot manufacture a pass, so it is not a relaxation"

    def test_write_refuses_when_a_gate_fails(self, lifecycle: dict[str, Any]) -> None:
        code, out, err = run(
            ["graduate", "--artifact", str(lifecycle["artifact"]), "--write", "--out-policy", "refused.yaml"]
        )
        assert code == 1, err or out
        assert not Path("refused.yaml").exists()
        assert "Nothing was written" in out or "not ready" in out.lower()

    def test_write_under_relaxed_gates_produces_a_servable_policy(self, lifecycle: dict[str, Any]) -> None:
        """The cutover itself: a new file, the local model as primary, the teacher as shadow."""
        dest = Path("graduated-relaxed.yaml")
        code, out, err = run(
            [
                "graduate",
                "--artifact",
                str(lifecycle["artifact"]),
                "--min-tier-agreement",
                "0.0",
                "--max-ece",
                "1.0",
                "--max-latency-ms",
                "100000",
                "--min-samples",
                "1",
                "--write",
                "--out-policy",
                str(dest),
            ]
        )
        assert code == 0, err or out
        assert dest.is_file()
        import yaml

        written = yaml.safe_load(dest.read_text(encoding="utf-8"))
        backend = written["backend"]
        assert backend["name"] == "shadow"
        assert backend["primary"]["name"] == "distilled"
        assert Path(backend["primary"]["artifact"]) == lifecycle["artifact"].resolve()
        assert backend["primary"]["feature_mode"] is True
        assert "primary builds DistilledBackend" in out, "the swap was not verified against the real factory"

    def test_the_written_policy_is_not_the_one_it_graduated_from(self, lifecycle: dict[str, Any]) -> None:
        code, out, _ = run(
            [
                "graduate",
                "--artifact",
                str(lifecycle["artifact"]),
                "--min-tier-agreement",
                "0.0",
                "--max-ece",
                "1.0",
                "--max-latency-ms",
                "100000",
                "--min-samples",
                "1",
                "--write",
            ]
        )
        assert code == 0
        assert "(new file)" in out
        assert not (REPO_ROOT / "policies" / "default-graduated.yaml").exists() or "new file" in out


