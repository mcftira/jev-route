"""End-to-end tests for the five graduation verbs, driven through the real CLI.

These exist because of a specific failure: ``export``, ``train``, ``evaluate``,
``package`` and ``graduate`` were all registered in :mod:`jev_route.cli` and all
five raised ``AttributeError: module 'jev_route.distill' has no attribute
'export_cli'``. The parser was complete, ``--help`` looked finished, and the
headline feature was 100% broken. A unit test of any one verb would not have
caught that, because the break was in the seam between the two modules -- so the
first test here drives ``jev_route.cli.main`` exactly as a shell would, and the
rest walk the whole lifecycle on a real log.

The log is generated by :mod:`tests.distill.synthlog`, which routes a prompt
corpus through the real Router with MockBackend, so the records being exported
are records the production code path could have written. No network, no API key:
``conftest.py``'s autouse ``_offline`` fixture removes the key and fails any
socket call, and every path below is inside ``tmp_path``.

What is deliberately *not* asserted: that the trained student is any good. It is
trained on ~120 synthetic decisions, so its tier agreement is nowhere near the
0.95 bar. The tests assert the verbs run, report, exit with the documented codes,
and refuse to write a policy they have not earned -- which is the behaviour under
test. ``tests/backends/test_distilled.py`` covers serving an artifact.
"""

from __future__ import annotations

import contextlib
import io
import json
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import pytest

from jev_route.cli import main
from tests.distill.synthlog import build_log

REPO_ROOT = Path(__file__).resolve().parents[1]
TRACEBACK = "Traceback (most recent call last)"
ENV_VARS = ("JEV_ROUTE_POLICY", "JEV_ROUTE_LOG", "JEV_ROUTE_DECISION_LOG", "JEV_ROUTE_ARTIFACT")


def _clean_env(monkeypatch: pytest.MonkeyPatch) -> None:
    """A leaked JEV_ROUTE_* would silently change which policy or log a verb picks."""
    for name in ENV_VARS:
        monkeypatch.delenv(name, raising=False)


def _require_numpy() -> None:
    try:
        import numpy  # noqa: F401
    except ImportError:  # pragma: no cover - depends on the environment
        pytest.skip("the distill extra is not installed: pip install 'jev-route[distill]'")


def run(argv: Sequence[str]) -> tuple[int, str, str]:
    """Run the CLI in-process and capture both streams.

    In-process rather than a subprocess because that is what makes a traceback
    visible as a test failure instead of a wall of stderr, and because it keeps
    the whole lifecycle inside one pytest session's import cache.
    """
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = main(list(argv))
    return int(code), out.getvalue(), err.getvalue()


def run_json(argv: Sequence[str]) -> tuple[int, dict[str, Any], str]:
    """Run a verb with ``--json`` and parse stdout, which must be nothing but JSON."""
    code, out, err = run([*argv, "--json"])
    try:
        return code, json.loads(out), err
    except json.JSONDecodeError as exc:  # pragma: no cover - a real failure, not a skip
        pytest.fail(f"--json printed something that is not JSON ({exc}):\n{out[:800]}")


@pytest.fixture(autouse=True)
def _isolated(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """Run from a directory with no policy file, so no test inherits the repo's."""
    _clean_env(monkeypatch)
    monkeypatch.chdir(tmp_path)


@pytest.fixture(scope="module")
def log_path(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """A real decision log: 140 records routed through the real Router, offline."""
    _require_numpy()
    target = tmp_path_factory.mktemp("logs") / "decisions.jsonl"
    # The log has to be written where the verbs will look for it, and the fixture
    # directory is not the per-test cwd, so it is built at an absolute path.
    stats = build_log(target, n=140, seed=11, excerpt_mode="hash")
    assert stats.records == 140
    return target


@pytest.fixture(scope="module")
def lifecycle(tmp_path_factory: pytest.TempPathFactory, log_path: Path) -> dict[str, Any]:
    """Run the whole lifecycle once, and hand every stage's result to the tests.

    One run rather than one per test because training dominates the cost, and
    because the point is that the stages chain: ``train`` reads what ``export``
    wrote, ``evaluate`` and ``package`` read what ``train`` wrote, and
    ``graduate`` reads what ``package`` wrote. A fixture per stage would let a
    broken hand-off pass unnoticed.
    """
    work = tmp_path_factory.mktemp("lifecycle")
    results: dict[str, Any] = {"work": work}

    results["export"] = run(["export", "--log", str(log_path), "--out", str(work / "ds")])
    dataset = work / "ds" / "dataset.jsonl"
    results["dataset"] = dataset
    assert dataset.is_file(), results["export"][2] or results["export"][1]

    results["train"] = run(["train", "--data", str(work / "ds"), "--out", str(work / "v1")])
    results["model"] = work / "v1"
    assert (work / "v1" / "artifact.json").is_file(), results["train"][2] or results["train"][1]

    results["evaluate"] = run(["evaluate", "--artifact", str(work / "v1")])
    results["evaluate_json"] = run_json(["evaluate", "--artifact", str(work / "v1")])

    results["package"] = run(["package", "--artifact", str(work / "v1"), "--out", str(work / "packaged")])
    results["artifact"] = work / "packaged"
    assert (work / "packaged" / "artifact.json").is_file(), results["package"][2] or results["package"][1]

    results["graduate"] = run(["graduate", "--artifact", str(work / "packaged"), "--min-samples", "1"])
    results["graduate_json"] = run_json(["graduate", "--artifact", str(work / "packaged"), "--min-samples", "1"])
    return results


# --------------------------------------------------------------------------- #
# the seam that was broken
# --------------------------------------------------------------------------- #
class TestTheVerbsAreWiredUp:
    """The regression test for five commands that parsed and did not exist."""

    @pytest.mark.parametrize(
        "verb",
        ["label_sensitivity_cli", "export_cli", "train_cli", "evaluate_cli", "package_cli", "graduate_cli"],
    )
    def test_the_package_exposes_the_verb(self, verb: str) -> None:
        from jev_route import distill

        assert callable(getattr(distill, verb)), f"jev_route.distill.{verb} is missing or not callable"

    def test_the_lazy_export_does_not_import_numpy(self) -> None:
        """``import jev_route`` has to stay numpy-free: the router runs in containers without it."""
        code = (
            "import sys, jev_route.distill as d;"
            "names = [getattr(d, n).__name__ for n in d.__all__];"
            "print(','.join(sorted(names)), 'numpy' in sys.modules)"
        )
        result = subprocess.run(
            [sys.executable, "-c", code], capture_output=True, text=True, timeout=120, cwd=str(REPO_ROOT)
        )
        assert result.returncode == 0, result.stderr
        names, numpy_loaded = result.stdout.strip().split()
        assert names == "evaluate_cli,export_cli,graduate_cli,label_sensitivity_cli,package_cli,train_cli"
        assert numpy_loaded == "False", "resolving the six verbs pulled numpy into the process"

    def test_export_runs_from_a_cold_start(self, log_path: Path, tmp_path: Path) -> None:
        """``export`` needs no numpy at all, so it works even without the extra."""
        code, out, err = run(["export", "--log", str(log_path), "--out", str(tmp_path / "cold")])
        assert code == 0, err or out
        assert TRACEBACK not in out + err


