class TestArgumentHandling:
    def test_the_deprecated_model_alias_still_works_and_says_so(self, lifecycle: dict[str, Any]) -> None:
        code, out, err = run(
            ["package", "--model", str(lifecycle["model"]), "--out", str(lifecycle["work"] / "via-alias")]
        )
        assert code == 0, err or out
        assert "--model is a deprecated alias for --artifact" in err
        assert "0.3.0" in err
        assert (lifecycle["work"] / "via-alias" / "artifact.json").is_file()
        assert "warning" not in out, "the warning belongs on stderr so --json stays parseable"

    def test_the_alias_warning_does_not_corrupt_json(self, lifecycle: dict[str, Any]) -> None:
        code, payload, err = run_json(
            ["package", "--model", str(lifecycle["model"]), "--out", str(lifecycle["work"] / "alias-json")]
        )
        assert code == 0, err
        assert "deprecated alias" in err
        assert payload["artifact"].endswith("alias-json")

    def test_the_new_spelling_does_not_warn(self, lifecycle: dict[str, Any]) -> None:
        code, _, err = run(
            ["package", "--artifact", str(lifecycle["model"]), "--out", str(lifecycle["work"] / "no-warn")]
        )
        assert code == 0, err
        assert "deprecated" not in err

    @pytest.mark.parametrize(
        ("argv", "needle"),
        [
            pytest.param(["package", "--out", "x"], "needs the trained model", id="neither-flag"),
            pytest.param(
                ["package", "--artifact", "a", "--model", "b", "--out", "x"],
                "not both",
                id="both-and-they-disagree",
            ),
        ],
    )
    def test_an_ambiguous_package_invocation_is_refused(self, argv: list[str], needle: str) -> None:
        code, out, err = run(argv)
        assert code == 2
        assert needle in err, err or out
        assert TRACEBACK not in out + err

    def test_both_flags_naming_the_same_path_is_not_an_error(self, lifecycle: dict[str, Any]) -> None:
        model = str(lifecycle["model"])
        code, _, err = run(["package", "--artifact", model, "--model", model, "--out", "same-path"])
        assert code == 0, err
        assert "deprecated" not in err, "--artifact was given, so the alias is not what the operator used"

    def test_an_explicit_policy_that_does_not_exist_is_an_error(self, lifecycle: dict[str, Any]) -> None:
        """Not a silent fallback: the gates are measured under the policy you named."""
        for argv in (
            ["graduate", "--artifact", str(lifecycle["artifact"]), "--policy", "nope.yaml"],
            ["evaluate", "--artifact", str(lifecycle["artifact"]), "--policy", "nope.yaml"],
        ):
            code, out, err = run(argv)
            assert code == 2, err or out
            assert "does not exist" in err
            assert TRACEBACK not in out + err


