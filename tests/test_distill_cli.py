class TestFailuresAreOneLine:
    @pytest.mark.parametrize(
        ("argv", "needle"),
        [
            pytest.param(["export", "--log", "gone.jsonl", "--out", "ds"], "decision log not found", id="export-log"),
            pytest.param(["train", "--data", "nodata", "--out", "v1"], "dataset not found", id="train-data"),
            pytest.param(["evaluate", "--artifact", "noartifact"], "no distilled artifact", id="evaluate-artifact"),
            pytest.param(
                ["package", "--artifact", "noartifact", "--out", "x"], "no distilled artifact", id="package-artifact"
            ),
            pytest.param(
                ["graduate", "--artifact", "noartifact", "--policy", str(REPO_ROOT / "policies" / "default.yaml")],
                "no distilled artifact",
                id="graduate-artifact",
            ),
        ],
    )
    def test_a_missing_input_is_actionable(self, argv: list[str], needle: str) -> None:
        code, out, err = run(argv)
        assert code == 2
        assert needle in err, err or out
        assert TRACEBACK not in out + err
        assert len([line for line in err.splitlines() if line.startswith("jev-route")]) == 1

    def test_bad_training_numbers_are_rejected_before_any_work(self, log_path: Path, tmp_path: Path) -> None:
        _require_numpy()
        run(["export", "--log", str(log_path), "--out", str(tmp_path / "ds")])
        for flag, value, needle in (
            ("--epochs", "0", "at least 1"),
            ("--lr", "0", "must be in"),
        ):
            code, out, err = run(["train", "--data", str(tmp_path / "ds"), "--out", str(tmp_path / "v"), flag, value])
            assert code == 2, err or out
            assert needle in err
            assert TRACEBACK not in out + err

    def test_replay_on_a_hash_mode_log_explains_why_it_cannot(self, lifecycle: dict[str, Any]) -> None:
        """The log retained no prompt text, so there is nothing to re-send to a teacher."""
        code, out, err = run(["graduate", "--artifact", str(lifecycle["artifact"]), "--replay", "--min-samples", "1"])
        assert code == 2
        combined = out + err
        assert "excerpt_mode" in combined or "redacted" in combined
        assert TRACEBACK not in combined

    def test_library_messages_name_only_real_cli_verbs(self) -> None:
        """Error advice must point at a verb ``jev-route --help`` lists.

        The four library modules were once written against a single ``jev-route
        distill`` verb the CLI never had; that is fixed at the source, so this
        pins it: no module in the package names the stale verb, and the
        load-bearing advice string names the real two-stage lifecycle.
        """
        import jev_route.distill as distill_pkg

        offenders = [py.name for py in sorted(Path(distill_pkg.__file__).resolve().parent.glob("*.py"))
                     if "jev-route distill" in py.read_text(encoding="utf-8")]
        assert offenders == []

        from jev_route.distill import artifact

        with pytest.raises(artifact.ArtifactError) as excinfo:
            artifact.load_artifact("/definitely/absent/artifact")
        assert "jev-route export --log" in str(excinfo.value)
        assert "jev-route train --data" in str(excinfo.value)
