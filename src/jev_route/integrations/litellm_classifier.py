#: jev_route.integrations.litellm_classifier.classifier`` with
#: ``get_instance_fn``, which requires the last dotted segment to be an
#: attribute holding an *instance* whose ``classify`` is a coroutine function.
classifier = JevRouteClassifier.from_env()

